/**
 * A very small .xlsx writer — one sheet of text and numbers with a few cell styles — so the portal can hand out
 * Excel files without pulling in a spreadsheet library. An .xlsx is a zip of XML files; the zip is written
 * uncompressed ("stored"), which every spreadsheet program reads.
 */

export type CellStyle = 'plain' | 'header' | 'label' | 'wrap' | 'title' | 'note';

export interface Cell {
  v: string | number;
  s?: CellStyle;
}

export interface SheetSpec {
  name: string;
  /** rows[r][c]; `null` leaves the cell empty. Column A is the first column. */
  rows: (Cell | string | number | null)[][];
  /** column widths, in characters */
  widths?: number[];
  /** row (1-based) to freeze under, if any */
  freezeRow?: number;
}

const STYLE_INDEX: Record<CellStyle, number> = { plain: 0, header: 1, label: 2, wrap: 3, title: 4, note: 5 };

const esc = (v: string) =>
  v.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c] as string)).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '');

const colName = (i: number) => {
  let n = i + 1;
  let out = '';
  while (n > 0) {
    const m = (n - 1) % 26;
    out = String.fromCharCode(65 + m) + out;
    n = Math.floor((n - 1) / 26);
  }
  return out;
};

function sheetXml(sheet: SheetSpec): string {
  const cols = (sheet.widths || []).map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const rows = sheet.rows
    .map((row, r) => {
      const cells = row
        .map((raw, c) => {
          if (raw === null || raw === undefined || raw === '') return '';
          const cell: Cell = typeof raw === 'object' ? raw : { v: raw };
          const ref = `${colName(c)}${r + 1}`;
          const st = STYLE_INDEX[cell.s || 'plain'];
          return typeof cell.v === 'number'
            ? `<c r="${ref}" s="${st}"><v>${cell.v}</v></c>`
            : `<c r="${ref}" s="${st}" t="inlineStr"><is><t xml:space="preserve">${esc(cell.v)}</t></is></c>`;
        })
        .join('');
      return cells ? `<row r="${r + 1}">${cells}</row>` : '';
    })
    .join('');
  const pane = sheet.freezeRow
    ? `<sheetViews><sheetView workbookViewId="0" showGridLines="0"><pane ySplit="${sheet.freezeRow}" topLeftCell="A${sheet.freezeRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>`
    : '<sheetViews><sheetView workbookViewId="0" showGridLines="0"/></sheetViews>';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${pane}<sheetFormatPr defaultRowHeight="15"/><cols>${cols}</cols><sheetData>${rows}</sheetData></worksheet>`;
}

