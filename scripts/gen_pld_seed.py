"""Generate src/data/pldSeed.ts from 'PLD template.xlsx' (the PLD Data template Kite sends to its vendors).

Run from the project root:  python scripts/gen_pld_seed.py
"""
import datetime
import json

import openpyxl

SRC = 'PLD template.xlsx'
OUT = 'src/data/pldSeed.ts'

# PLD fields whose value is picked from a field of the Kite dictionary
DICT_LINK = {
    'Partner_Name': 'src', 'Brand': 'brd', 'Indication': 'indc', 'Channel': 'chnl', 'Activity_Name': 'act_nm',
    'Device_Type': 'devc_nm', 'Asset_ID': 'aset_id', 'Country': 'country',
}

# vendor names are replaced with neutral wording
def neutral(t):
    t = t.replace('Evoke - Kite', 'Agency - Kite').replace('defined by Evoke', 'defined by the agency')
    return t.replace('Evoke', 'Agency')


ws = openpyxl.load_workbook(SRC).active
rows, tail = [], []
for r in ws.iter_rows(min_row=5, values_only=True):
    r = list(r[1:9])
    if isinstance(r[0], int):
        ex = r[7]
        if isinstance(ex, datetime.datetime):
            ex = ex.strftime('%Y/%m/%d %H:%M:%S')
        rows.append({
            'segment': (r[1] or '').strip(), 'name': (r[2] or '').strip(), 'definition': neutral((r[3] or '').strip()),
            'required': (r[4] or '').strip(), 'metadata': (r[5] or '').strip(), 'managedBy': neutral((r[6] or '').strip()),
            'example': '' if ex is None else str(ex).strip(), 'dictField': DICT_LINK.get((r[2] or '').strip(), ''),
        })
    elif r[1] and (str(r[1]).startswith('Examples of') or tail):
        tail.append([str(x).strip() if x else '' for x in r[1:4]])
tail = [t for t in tail if any(t)]

src = ws['D1'].value, ws['D2'].value
with open(OUT, 'w', encoding='utf-8') as f:
    f.write("// GENERATED by scripts/gen_pld_seed.py from 'PLD template.xlsx' — do not edit by hand.\n\n")
    f.write("export interface PldSeedRow {\n  segment: string;\n  name: string;\n  definition: string;\n  required: string;\n  metadata: string;\n  managedBy: string;\n  example: string;\n  /** key of the dictionary field the example is picked from, when there is one */\n  dictField: string;\n}\n\n")
    f.write(f"export const PLD_FILE_FORMAT = {json.dumps(str(src[0]).strip())};\n")
    f.write(f"export const PLD_NAMING = {json.dumps(str(src[1]).strip().replace(chr(160), ''))};\n\n")
    f.write(f"export const PLD_SEED: PldSeedRow[] = {json.dumps(rows, indent=2, ensure_ascii=False)};\n\n")
    f.write(f"export const PLD_CUSTOM_EXAMPLES: string[][] = {json.dumps(tail, indent=2, ensure_ascii=False)};\n")
print(len(rows), 'rows;', tail[:2])
