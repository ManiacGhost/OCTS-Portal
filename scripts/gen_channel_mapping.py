"""Generate src/data/channelMappingSeed.ts from Kite_Channel_Subchannel_Publisher_Mapping_v1.xlsx.

One row per channel / sub-channel / publisher. Run from the project root:  python scripts/gen_channel_mapping.py
(Run scripts/gen_kite_dictionary.py too: it takes the channel, sub-channel and publisher values from the same file.)
"""
import json

import openpyxl

SRC = 'Kite_Channel_Subchannel_Publisher_Mapping_v1.xlsx'
OUT = 'src/data/channelMappingSeed.ts'

rows = list(openpyxl.load_workbook(SRC, data_only=True).active.iter_rows(values_only=True))
head = next(i for i, r in enumerate(rows) if r and str(r[0] or '').strip() == 'Channel')
out = []
for r in rows[head + 1:]:
    if not r or not r[0] or not r[1]:
        continue
    channel, sub, publisher, ctype, required = [str(x or '').strip() for x in r[:5]]
    out.append({'channel': channel, 'subChannel': sub, 'publisher': publisher, 'channelType': ctype,
                'publisherRequired': 'auto' if required.lower() == 'auto' else 'yes'})

with open(OUT, 'w', encoding='utf-8') as f:
    f.write(f'// GENERATED by scripts/gen_channel_mapping.py from {SRC}; do not edit by hand.\n\n')
    f.write('export interface ChannelMappingRow {\n  channel: string;\n  subChannel: string;\n  publisher: string;\n'
            '  /** 3P Publisher, Owned Platform, Field or Pending */\n  channelType: string;\n'
            '  /** "auto": the publisher is fixed by the channel and filled in; "yes": the user picks it */\n'
            "  publisherRequired: 'auto' | 'yes';\n}\n\n")
    f.write('export const CHANNEL_MAPPING: ChannelMappingRow[] = ' + json.dumps(out, indent=2, ensure_ascii=False) + ';\n')
print(len(out), 'rows ->', OUT)
