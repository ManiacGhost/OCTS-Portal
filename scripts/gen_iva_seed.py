"""Generate src/data/ivaSeed.ts from Kite_IVA_Content_Tagging_Yescarta_HCP_v1.xlsx (sheet IVA_Content_Tagging).

One row per slide: the header row starts with "Page #"; rows without a topic (the deck itself, shared
resources, footer notes) are left out. Run from the project root:  python scripts/gen_iva_seed.py
"""
import json
from collections import Counter

import openpyxl

SRC = 'Kite_IVA_Content_Tagging_Yescarta_HCP_v1.xlsx'
OUT = 'src/data/ivaSeed.ts'

ws = openpyxl.load_workbook(SRC, data_only=True)['IVA_Content_Tagging']
rows = list(ws.iter_rows(values_only=True))
head = next(i for i, r in enumerate(rows) if r and str(r[0] or '').strip() == 'Page #')
cols = [str(h or '').strip() for h in rows[head]]
col = {name: cols.index(name) for name in cols if name}


def cell(r, name):
    v = r[col[name]] if col[name] < len(r) else None
    v = '' if v is None else str(v).strip()
    return '' if v in ('-', 'N/A') else v


slides = []
for r in rows[head + 1:]:
    if not r or not cell(r, 'Topic (VVPM, governed)'):
        continue
    slides.append({
        'page': cell(r, 'Page #'),
        'promomatsId': cell(r, 'Promomats ID'),
        'document': cell(r, 'Document Number'),
        'title': cell(r, 'Title (interface display)'),
        'keyMessage': cell(r, 'Key Message (CTAM rep pick)'),
        'topic': cell(r, 'Topic (VVPM, governed)'),
        'subtopic': cell(r, 'Subtopic (VVPM)'),
        'crmValue': cell(r, 'Mapped CRM dropdown value'),
    })

# a slide the sheet has no CRM value for gets the one most used with its key message (or, failing that, its
# topic), and is marked "suggested" so it can be told apart from a mapped value
by_km = {}
by_topic = {}
for s in slides:
    if s['crmValue']:
        by_km.setdefault(s['keyMessage'].lower(), Counter())[s['crmValue']] += 1
        by_topic.setdefault(s['topic'].lower(), Counter())[s['crmValue']] += 1
for s in slides:
    s['crmSuggested'] = False
    if not s['crmValue']:
        pool = by_km.get(s['keyMessage'].lower()) or by_topic.get(s['topic'].lower())
        if pool:
            s['crmValue'] = pool.most_common(1)[0][0]
            s['crmSuggested'] = True

with open(OUT, 'w', encoding='utf-8') as f:
    f.write(f"// GENERATED by scripts/gen_iva_seed.py from {SRC}; do not edit by hand.\n\n")
    f.write('export interface IvaSlide {\n  page: string;\n  promomatsId: string;\n  document: string;\n  title: string;\n'
            '  keyMessage: string;\n  topic: string;\n  subtopic: string;\n  crmValue: string;\n'
            '  /** the sheet has no CRM value for this slide: this one is suggested from slides with the same key message */\n'
            '  crmSuggested: boolean;\n}\n\n')
    f.write('export const IVA_DECK = ' + json.dumps({'name': 'Yescarta HCP IVA', 'brand': 'YESCARTA', 'audience': 'HCP'}) + ';\n\n')
    f.write('export const IVA_SLIDES: IvaSlide[] = ' + json.dumps(slides, indent=2, ensure_ascii=False) + ';\n')
print(len(slides), 'slides,', sum(s['crmSuggested'] for s in slides), 'with a suggested CRM value ->', OUT)
